-- Tables for the PostgreSQL node. Run on bpjsk_poc as the table owner
-- (developer), first, before postgres-02-replication.sql and
-- postgres-03-lww-trigger.sql. Safe to re-run: each table is only created when
-- missing (existing tables are left as they are, so this does not migrate a
-- changed definition). Create the database itself beforehand, e.g.
--   CREATE DATABASE bpjsk_poc OWNER developer;
--
-- Must stay in step with mssql-01-schema.sql: same columns (snake_case here,
-- PascalCase there; the sinks' ReplaceField renames map one to the other),
-- compatible types and nullability, same unique keys, same total_amount formula.
--
-- Keys: identity columns; postgres-02-replication.sql moves their sequences to
-- 1000000000 so this node's keys never overlap SQL Server's (1..999999999).
-- BY DEFAULT (not ALWAYS) so the sink can insert SQL Server's keys.
-- Keys are INTEGER to match SQL Server's INT (both sides must agree on int32).
-- Timestamps are timestamptz (UTC on the wire). Audit users: SQL Server
-- < 1000000, PostgreSQL >= 1000000.

CREATE TABLE IF NOT EXISTS public.bpjs_membership (
    membership_id    integer GENERATED BY DEFAULT AS IDENTITY,
    employee_id      integer       NOT NULL,
    bpjs_number      varchar(20)   NOT NULL,
    nik              varchar(16)   NOT NULL,
    full_name        varchar(150)  NOT NULL,
    enrollment_date  date          NOT NULL,
    work_risk_group  integer       NOT NULL DEFAULT 1,
    is_active        boolean       NOT NULL DEFAULT true,
    created_at       timestamptz            DEFAULT now(),
    created_by       integer,
    updated_by       integer,
    updated_at       timestamptz,
    deleted_by       integer,
    deleted_at       timestamptz,
    CONSTRAINT bpjs_membership_pkey PRIMARY KEY (membership_id),
    CONSTRAINT bpjs_membership_bpjs_number_key UNIQUE (bpjs_number),
    CONSTRAINT bpjs_membership_nik_key UNIQUE (nik)
);

CREATE TABLE IF NOT EXISTS public.bpjs_monthly_contribution (
    contribution_id  integer GENERATED BY DEFAULT AS IDENTITY,
    membership_id    integer        NOT NULL,
    period_month     smallint       NOT NULL,
    period_year      smallint       NOT NULL,
    base_wage        numeric(18, 2) NOT NULL,
    jht_employee     numeric(18, 2) NOT NULL DEFAULT 0,
    jht_employer     numeric(18, 2) NOT NULL DEFAULT 0,
    jkk_employer     numeric(18, 2) NOT NULL DEFAULT 0,
    jkm_employer     numeric(18, 2) NOT NULL DEFAULT 0,
    jp_employee      numeric(18, 2) NOT NULL DEFAULT 0,
    jp_employer      numeric(18, 2) NOT NULL DEFAULT 0,
    -- Computed on each node and never replicated (both sinks drop it). Same
    -- formula as TotalAmount in mssql-01-schema.sql.
    total_amount     numeric(18, 2) GENERATED ALWAYS AS
                     (jht_employee + jht_employer + jkk_employer + jkm_employer + jp_employee + jp_employer) STORED,
    payment_status   varchar(30)    NOT NULL DEFAULT 'UNPAID',
    paid_at          timestamptz,
    created_at       timestamptz             DEFAULT now(),
    created_by       integer,
    updated_by       integer,
    updated_at       timestamptz,
    deleted_by       integer,
    deleted_at       timestamptz,
    CONSTRAINT bpjs_monthly_contribution_pkey PRIMARY KEY (contribution_id),
    CONSTRAINT bpjs_monthly_contribution_period_key UNIQUE (membership_id, period_year, period_month),
    CONSTRAINT bpjs_monthly_contribution_period_month_check CHECK (period_month BETWEEN 1 AND 12),
    CONSTRAINT bpjs_monthly_contribution_membership_fkey FOREIGN KEY (membership_id)
        REFERENCES public.bpjs_membership (membership_id)
);

CREATE TABLE IF NOT EXISTS public.bpjs_claim (
    claim_id           integer GENERATED BY DEFAULT AS IDENTITY,
    membership_id      integer        NOT NULL,
    claim_number       varchar(30)    NOT NULL,
    program_type       varchar(10)    NOT NULL,   -- JHT, JKK, JKM, JP, JKP
    claim_date         date           NOT NULL,
    reason_description varchar(500)   NOT NULL,
    disbursed_amount   numeric(18, 2),
    claim_status       varchar(30)    NOT NULL DEFAULT 'SUBMITTED',
    approved_at        timestamptz,
    created_at         timestamptz             DEFAULT now(),
    created_by         integer,
    updated_by         integer,
    updated_at         timestamptz,
    deleted_by         integer,
    deleted_at         timestamptz,
    CONSTRAINT bpjs_claim_pkey PRIMARY KEY (claim_id),
    CONSTRAINT bpjs_claim_claim_number_key UNIQUE (claim_number),
    CONSTRAINT bpjs_claim_membership_fkey FOREIGN KEY (membership_id)
        REFERENCES public.bpjs_membership (membership_id)
);

-- FK columns are not indexed automatically.
CREATE INDEX IF NOT EXISTS bpjs_claim_membership_id_idx ON public.bpjs_claim (membership_id);
-- (bpjs_monthly_contribution.membership_id is covered by its period unique key.)
